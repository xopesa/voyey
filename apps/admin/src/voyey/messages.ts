export const translate = (locale: Locale, key: MessageKey) =>
  copy[key][locale === "uz" ? 1 : 0];
export const money = (amount: number, locale: Locale) =>
  new Intl.NumberFormat(locale === "uz" ? "uz-UZ" : "ru-RU", {
    style: "currency",
    currency: "UZS",
    maximumFractionDigits: 0,
  }).format(amount);
export const dateTime = (date: string, locale: Locale) =>
  new Intl.DateTimeFormat(locale === "uz" ? "uz-UZ" : "ru-RU", {
    timeZone: "Asia/Tashkent",
    day: "2-digit",
    month: "short",
    hour: "2-digit",
    minute: "2-digit",
  }).format(new Date(date));
