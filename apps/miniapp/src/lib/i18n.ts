export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: Record<string, string | number>,
): string {
  return messages[locale][key].replace(
    /\{(\w+)\}/g,
    (placeholder, name: string) =>
      values?.[name] === undefined ? placeholder : String(values[name]),
  );
}

// Presentation-only selection for nameRu/nameUz and descriptionRu/descriptionUz.
export function localizedText(
  locale: Locale,
  values: Record<Locale, string | null | undefined>,
): string {
  return values[locale] || values.ru || values.uz || "";
}
